"""Per-case comparison of A, C4 (default), C4 + semantic route and C6 + semantic route (fab09130).

Writes PER-CASE.md from the committed runs: the development union (dev/runs, same runner file)
and the reviewer's unseen set (review/, reviewer harness). Cell: P/- strict pass, needed
returned / needed, x extras (returned memories outside must ∪ may).
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
COLS = ("A", "C4", "C4+sem", "C6+sem")


def dev_rows():
    expect, meta, runs = {}, {}, {c: {} for c in COLS}
    for name in ("diag", "c5-dev"):
        for s in json.load(open(HERE / "dev" / f"{name}-scenarios.json"))["scenarios"]:
            for q in s["queries"]:
                expect[f"{name}:{q['id']}"] = q["expect"]
                meta[f"{name}:{q['id']}"] = (q.get("kind", "c5-dev"), q["query"])
        for col, label in zip(COLS, ("A-off", "C4-off", "C4-sem", "C6-sem")):
            for s in json.load(open(HERE / "dev" / "runs" / f"{label}-{name}.json"))["scenarios"]:
                for q in s["queries"]:
                    i = f"{name}:{q['id']}"
                    must = set(expect[i].get("must_include") or [])
                    allowed = must | set(expect[i].get("may_include") or [])
                    runs[col][i] = (q["passed"], len(must & set(q["returned"])), len(must),
                                    len([r for r in q["returned"] if r not in allowed]))
    return meta, runs


def gen_rows():
    files = {"A": "review/after-fixes/A-gen-off.json", "C4": "review/outputs/runs-gen-c4-off.json",
             "C4+sem": "review/outputs/runs-gen-c4-required.json", "C6+sem": "review/after-fixes/c6fix-gen-required.json"}
    meta, runs = {}, {c: {} for c in COLS}
    for col, f in files.items():
        for q in json.load(open(HERE / f)):
            meta[q["id"]] = (q["kind"], q["query"])
            runs[col][q["id"]] = (q["pass"], q["needed_returned"], q["needed"], q["extra"])
    return meta, runs


def table(title, meta, runs):
    out = [f"## {title}", "", "| id | kind | query | " + " | ".join(COLS) + " |", "|---|---|---|" + "---|" * len(COLS)]
    for i, (kind, query) in meta.items():
        cells = []
        for c in COLS:
            p, got, need, extra = runs[c][i]
            cells.append(f"{'P' if p else '-'} {got}/{need} x{extra}")
        out.append(f"| {i} | {kind} | {query.replace('|', '/')} | " + " | ".join(cells) + " |")
    tot = []
    for c in COLS:
        rows = runs[c].values()
        need = sum(r[2] for r in rows)
        tot.append(f"**{sum(bool(r[0]) for r in rows)}** {sum(r[1] for r in rows)}/{need} x{sum(r[3] for r in rows)}")
    out.append("| **total** | | | " + " | ".join(tot) + " |")
    return "\n".join(out) + "\n"


dev_meta, dev_runs = dev_rows()
gen_meta, gen_runs = gen_rows()
(HERE / "PER-CASE.md").write_text(
    "# C6 per-case comparison: A, C4, C4 + semantic route, C6 + semantic route\n\n"
    "Generated by `per_case.py`. Each cell gives `P` or `-` for strict pass, then needed memories returned out of needed, then `x` and the count of returned memories outside must ∪ may.\n\n"
    "- **A** is `7c06468a`. **C4** is `bc2be631` (default selection, semantic route off). **C4+sem** is C4 with `semantic_retrieval=\"required\"`. **C6+sem** is `fab09130` with `semantic_retrieval=\"required\"`.\n"
    "- **Development union:** self-authored, used for calibration, so these results are in-sample.\n"
    "- **Reviewer set:** written by the independent reviewer and unseen by calibration.\n"
    "- **Neither is held-out evidence.**\n\n"
    + table("Development union (78 queries, in-sample)", dev_meta, dev_runs) + "\n"
    + table("Reviewer set (55 queries, unseen by calibration)", gen_meta, gen_runs))

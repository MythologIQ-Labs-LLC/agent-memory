#!/usr/bin/env python3
"""Render/check every registered Runtime Baseline from its machine-readable record (#638, #674)."""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from check_runtime_baseline_equivalence import (  # noqa: E402
    DEFAULT_REGISTER,
    load_register,
    qualification_block,
)

ROOT = Path(__file__).resolve().parents[1]


def baseline_label(baseline_id: str) -> str:
    match = re.fullmatch(r"agent-memory-runtime-baseline-(v[0-9]+)", baseline_id)
    if not match:
        raise SystemExit(f"baseline_id {baseline_id!r} does not name a numbered Runtime Baseline")
    return match.group(1)



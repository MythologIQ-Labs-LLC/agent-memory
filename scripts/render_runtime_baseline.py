def validate(data: dict) -> None:
    required = {"schema_version", "baseline_id", "runtime_revision", "identity", "public_runtime_contract", "persistence_and_durability", "write_semantics", "read_semantics", "capabilities", "governance_invariants", "qualification_evidence", "known_limitations", "dogfood", "drift_policy"}
    missing = required - set(data)
    if missing:
        raise SystemExit(f"baseline manifest missing required keys: {sorted(missing)}")
    commit = data["runtime_revision"]["commit"]
    if len(commit) != 40 or any(ch not in "0123456789abcdef" for ch in commit):
        raise SystemExit("runtime_revision.commit must be an exact lowercase 40-hex SHA")
    if data["production_1_0"]:
        raise SystemExit("a Runtime Baseline must not claim production 1.0")
    if data["authority_effect"] != "none":
        raise SystemExit("baseline authority_effect must remain none")
    if data["dogfood"].get("required_before_issue_638_close", True) is not True:
        raise SystemExit("public Gauntlet dogfood must remain a close gate")


def render_entry(root: Path, entry: dict) -> tuple[Path, str]:
    record_path = entry["record"]
    data = json.loads((root / record_path).read_text(encoding="utf-8"))
    validate(data)
    public_gauntlet = qualification_block(root, entry)
    output = (root / record_path).with_suffix(".md")
    return output, render(data, public_gauntlet, record_path)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--register", type=Path, default=DEFAULT_REGISTER)
    parser.add_argument("--baseline", action="append", default=[], help="baseline_id to render (default: every entry)")
    parser.add_argument("--root", type=Path, default=ROOT, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    root = args.root.resolve()
    register = load_register(root, args.register)
    entries = [entry for entry in register["baselines"] if not args.baseline or entry["baseline_id"] in args.baseline]
    if args.baseline and len(entries) != len(set(args.baseline)):
        raise SystemExit(f"unknown baseline id among {args.baseline}")
    for entry in entries:
        output, rendered = render_entry(root, entry)
        if args.check:
            current = output.read_text(encoding="utf-8") if output.exists() else ""
            if current != rendered:
                raise SystemExit(f"{output.relative_to(root)} drifted; run scripts/render_runtime_baseline.py")
            continue
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(rendered, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
